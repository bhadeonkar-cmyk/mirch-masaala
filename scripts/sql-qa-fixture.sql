CREATE TABLE public.mm_restaurant_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id uuid NOT NULL REFERENCES public.restaurants(id) ON DELETE CASCADE,
  target_role text NOT NULL CHECK (target_role IN ('admin','waiter','kitchen')),
  notification_type text NOT NULL CONSTRAINT mm_restaurant_notifications_notification_type_check
    CHECK (notification_type IN ('WAITER_CALL','BILL_REQUEST','NEW_ORDER','ORDER_READY','ITEM_SOLD_OUT')),
  table_number text NOT NULL DEFAULT '',
  ticket_id text NOT NULL DEFAULT '',
  item_name text NOT NULL DEFAULT '',
  message text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz,
  resolved_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE TABLE public.restaurant_tables (
  id uuid PRIMARY KEY,
  restaurant_id uuid NOT NULL,
  table_number text NOT NULL,
  is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE public.menu_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  restaurant_id uuid NOT NULL,
  name text NOT NULL,
  price numeric(12,2) NOT NULL DEFAULT 0,
  is_available boolean NOT NULL DEFAULT true,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  restaurant_id uuid NOT NULL,
  table_id uuid NOT NULL REFERENCES public.restaurant_tables(id),
  status text NOT NULL,
  notes text,
  total numeric(12,2) NOT NULL DEFAULT 0,
  ticket_id text,
  public_token uuid NOT NULL DEFAULT gen_random_uuid(),
  order_number bigint GENERATED BY DEFAULT AS IDENTITY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_qa_orders_ticket_id
  ON public.orders (ticket_id) WHERE ticket_id IS NOT NULL;

CREATE TABLE public.order_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id uuid NOT NULL REFERENCES public.orders(id),
  menu_item_id uuid,
  item_name text NOT NULL,
  quantity integer NOT NULL DEFAULT 1,
  price numeric(12,2) NOT NULL DEFAULT 0,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);
