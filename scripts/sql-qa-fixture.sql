-- Minimal Supabase-like schema fixture for isolated accounting integration tests.
-- These tables exist only in the temporary PostgreSQL service used by GitHub Actions.
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;

CREATE SCHEMA auth;
CREATE TABLE auth.users (id uuid PRIMARY KEY);

CREATE OR REPLACE FUNCTION auth.uid()
RETURNS uuid
LANGUAGE sql
STABLE
AS $$
  SELECT NULLIF(current_setting('app.qa_uid', true), '')::uuid
$$;

CREATE OR REPLACE FUNCTION public.get_my_staff_role()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT NULLIF(current_setting('app.qa_role', true), '')
$$;

CREATE TABLE public.restaurant_tables (
  id uuid PRIMARY KEY,
  restaurant_id uuid NOT NULL,
  table_number text NOT NULL,
  is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE public.menu_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  restaurant_id uuid NOT NULL,
  name text NOT NULL,
  price numeric(12,2) NOT NULL DEFAULT 0,
  is_available boolean NOT NULL DEFAULT true,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  restaurant_id uuid NOT NULL,
  table_id uuid NOT NULL REFERENCES public.restaurant_tables(id),
  status text NOT NULL,
  notes text,
  total numeric(12,2) NOT NULL DEFAULT 0,
  ticket_id text,
  public_token uuid NOT NULL DEFAULT gen_random_uuid(),
  order_number bigint GENERATED BY DEFAULT AS IDENTITY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_qa_orders_ticket_id
  ON public.orders (ticket_id) WHERE ticket_id IS NOT NULL;

CREATE TABLE public.order_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id uuid NOT NULL REFERENCES public.orders(id),
  menu_item_id uuid,
  item_name text NOT NULL,
  quantity integer NOT NULL DEFAULT 1,
  price numeric(12,2) NOT NULL DEFAULT 0,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);
