STABLE
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
BEGIN
  IF public.get_my_staff_role() IS DISTINCT FROM 'admin' THEN RAISE EXCEPTION 'Owner/Admin access required'; END IF;
  RETURN jsonb_build_object(
    'last_backup_at',(SELECT max(e.created_at) FROM public.mm_admin_maintenance_events e
      WHERE e.restaurant_id='a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid AND e.action='BACKUP_EXPORTED'),
    'last_reset_at',(SELECT max(e.created_at) FROM public.mm_admin_maintenance_events e
      WHERE e.restaurant_id='a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid AND e.action='RESET_COMPLETED')
  );
END
$$;

CREATE OR REPLACE FUNCTION public.mm_admin_reset_business_data(
  p_confirmation text,
  p_backup_made boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
DECLARE
  v_restaurant_id uuid := 'a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid;
  v_name text;
  v_relation regclass;
  v_count integer;
  v_deleted jsonb := '{}'::jsonb;
  v_assignments text[] := ARRAY[]::text[];
  v_setting record;
BEGIN
  IF public.get_my_staff_role() IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Only the Owner/Admin can reset restaurant data';
  END IF;
  IF p_confirmation IS DISTINCT FROM 'RESET MIRCH MASAALA' THEN
    RAISE EXCEPTION 'Reset confirmation did not match. No data was changed.';
  END IF;

  -- Children first: payment rows restrict order deletion; order items belong to orders.
  FOREACH v_name IN ARRAY ARRAY[
    'order_payments','order_items','order_management_audit','mm_whatsapp_broadcast_logs',
    'mm_restaurant_notifications','mm_party_bookings','mm_restaurant_reviews',
    'mm_customer_profiles','orders','restaurant_table_visits','restaurant_settings','mm_whatsapp_settings'
  ] LOOP
    v_relation := to_regclass(format('public.%I',v_name));
    IF v_relation IS NULL THEN CONTINUE; END IF;

    IF v_name = 'order_items' THEN
      IF to_regclass('public.orders') IS NOT NULL THEN
        EXECUTE 'DELETE FROM public.order_items i USING public.orders o WHERE i.order_id=o.id AND o.restaurant_id=$1'
          USING v_restaurant_id;
      ELSE
        CONTINUE;
      END IF;
    ELSIF EXISTS (
      SELECT 1 FROM pg_attribute
      WHERE attrelid=v_relation AND attname='restaurant_id' AND NOT attisdropped
    ) THEN
      EXECUTE format('DELETE FROM public.%I WHERE restaurant_id=$1',v_name) USING v_restaurant_id;
    ELSE
      -- A table without restaurant_id is never cleared by a multi-restaurant reset.
      CONTINUE;
    END IF;
    GET DIAGNOSTICS v_count = ROW_COUNT;
    v_deleted := v_deleted || jsonb_build_object(v_name,v_count);
  END LOOP;

  -- Keep the menu and prices, but make previously sold-out dishes available for the fresh start.
  IF to_regclass('public.menu_items') IS NOT NULL
     AND EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='public.menu_items'::regclass AND attname='restaurant_id' AND NOT attisdropped)
     AND EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='public.menu_items'::regclass AND attname='is_available' AND NOT attisdropped) THEN
    EXECUTE 'UPDATE public.menu_items SET is_available=true WHERE restaurant_id=$1' USING v_restaurant_id;
  END IF;
  -- Reset shared customer-facing configuration to safe defaults when that optional table exists.
  IF to_regclass('public.mm_restaurant_config') IS NOT NULL THEN
    FOR v_setting IN
      SELECT * FROM (VALUES
        ('restaurant_name','MIRCH MASAALA'),
        ('tagline','INDIAN RESTAURANT'),
        ('admin_phone','+91 9657076450'),
        ('upi_id',''),
        ('upi_name','Mirch Masaala'),
        ('whatsapp_number','919657076450'),
        ('whatsapp_name','Mirch Masaala'),
        ('google_reviews_url',''),
        ('phonepe_upi',''),
        ('pay_note','Review the amount in your payment app before paying.')
      ) AS defaults(column_name,column_value)
    LOOP
      IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='public.mm_restaurant_config'::regclass AND attname=v_setting.column_name AND NOT attisdropped) THEN
        v_assignments := array_append(v_assignments,format('%I = %L',v_setting.column_name,v_setting.column_value));
      END IF;
    END LOOP;
    IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='public.mm_restaurant_config'::regclass AND attname='accept_card' AND NOT attisdropped) THEN
      v_assignments := array_append(v_assignments,'accept_card = true');
    END IF;
    IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='public.mm_restaurant_config'::regclass AND attname='accept_cash' AND NOT attisdropped) THEN
      v_assignments := array_append(v_assignments,'accept_cash = true');
    END IF;
    IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='public.mm_restaurant_config'::regclass AND attname='updated_at' AND NOT attisdropped) THEN
      v_assignments := array_append(v_assignments,'updated_at = now()');
    END IF;
    IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='public.mm_restaurant_config'::regclass AND attname='updated_by' AND NOT attisdropped) THEN
      v_assignments := array_append(v_assignments,'updated_by = NULL');
    END IF;
    IF cardinality(v_assignments) > 0 THEN
      EXECUTE format('UPDATE public.mm_restaurant_config SET %s WHERE restaurant_id=$1',array_to_string(v_assignments,', '))
        USING v_restaurant_id;
    END IF;
  END IF;

  INSERT INTO public.mm_admin_maintenance_events(restaurant_id,action,created_by,details)
  VALUES (v_restaurant_id,'RESET_COMPLETED',auth.uid(),jsonb_build_object('deleted_counts',v_deleted,'backup_made',coalesce(p_backup_made,false)));

  -- Treat the pre-reset export as the latest backup so the next 10-day reminder starts now.
  IF coalesce(p_backup_made,false) THEN
    INSERT INTO public.mm_admin_maintenance_events(restaurant_id,action,created_by,details)
    VALUES (v_restaurant_id,'BACKUP_EXPORTED',auth.uid(),jsonb_build_object('source','backup downloaded immediately before reset'));
  END IF;

  RETURN jsonb_build_object('ok',true,'deleted_counts',v_deleted,'backup_made',coalesce(p_backup_made,false),
    'message','Service records cleared and app settings reset. Menu prices, table list, waiter names and staff logins were kept.');
END
$$;

