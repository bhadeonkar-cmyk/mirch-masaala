-- Mirch Masaala owner operations toolkit.
-- Adds named waiter management, a downloadable scoped database backup, a 10-day reminder status,
-- and a guarded business-data reset. Run after supabase/setup-live.sql.
-- This migration deliberately does not depend on notification/party-booking/WhatsApp migrations:
-- those tables are included and reset only when they exist.

BEGIN;

DO $preflight$
BEGIN
  IF to_regclass('public.restaurants') IS NULL
     OR to_regclass('public.restaurant_tables') IS NULL
     OR to_regclass('public.orders') IS NULL
     OR to_regclass('public.order_items') IS NULL
     OR to_regprocedure('public.get_my_staff_role()') IS NULL THEN
    RAISE EXCEPTION 'Run supabase/setup-live.sql first. No data was changed.';
  END IF;
END
$preflight$;

CREATE TABLE IF NOT EXISTS public.mm_waiter_directory (
  restaurant_id uuid NOT NULL REFERENCES public.restaurants(id) ON DELETE CASCADE,
  waiter_code text NOT NULL,
  display_name text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (restaurant_id, waiter_code),
  CONSTRAINT mm_waiter_directory_code_check CHECK (waiter_code ~ '^W[0-9]{2,3}$'),
  CONSTRAINT mm_waiter_directory_name_check CHECK (char_length(btrim(display_name)) BETWEEN 1 AND 80)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_mm_waiter_directory_name
  ON public.mm_waiter_directory (restaurant_id, lower(display_name));

ALTER TABLE public.mm_waiter_directory ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.mm_waiter_directory FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS public.mm_admin_maintenance_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id uuid NOT NULL REFERENCES public.restaurants(id) ON DELETE CASCADE,
  action text NOT NULL CHECK (action IN ('BACKUP_EXPORTED','RESET_COMPLETED')),
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS ix_mm_admin_maintenance_events_recent
  ON public.mm_admin_maintenance_events (restaurant_id, action, created_at DESC);
ALTER TABLE public.mm_admin_maintenance_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.mm_admin_maintenance_events FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.mm_list_waiters(p_include_inactive boolean DEFAULT false)
RETURNS TABLE(waiter_code text, display_name text, active boolean, created_at timestamptz)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
DECLARE
  v_role text := public.get_my_staff_role();
BEGIN
  IF v_role IS NULL OR v_role NOT IN ('admin','waiter') THEN
    RAISE EXCEPTION 'Owner or waiter sign-in required';
  END IF;
  RETURN QUERY
  SELECT w.waiter_code, w.display_name, w.active, w.created_at
  FROM public.mm_waiter_directory w
  WHERE w.restaurant_id = 'a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid
    AND (w.active OR (v_role = 'admin' AND coalesce(p_include_inactive, false)))
  ORDER BY w.active DESC, w.waiter_code;
END
$$;

CREATE OR REPLACE FUNCTION public.mm_admin_save_waiter(
  p_display_name text,
  p_waiter_code text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
DECLARE
  v_role text := public.get_my_staff_role();
  v_name text := regexp_replace(btrim(coalesce(p_display_name,'')), '[[:space:]]+', ' ', 'g');
  v_code text := upper(btrim(coalesce(p_waiter_code,'')));
  v_row public.mm_waiter_directory%ROWTYPE;
BEGIN
  IF v_role IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Only the Owner/Admin can manage waiter names';
  END IF;
  IF char_length(v_name) < 1 OR char_length(v_name) > 80 THEN
    RAISE EXCEPTION 'Enter a waiter name between 1 and 80 characters';
  END IF;

  IF v_code <> '' THEN
    IF v_code !~ '^W[0-9]{2,3}$' THEN RAISE EXCEPTION 'Invalid internal waiter ID'; END IF;
    UPDATE public.mm_waiter_directory
    SET display_name = v_name, updated_at = now()
    WHERE restaurant_id = 'a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid
      AND waiter_code = v_code
    RETURNING * INTO v_row;
    IF NOT FOUND THEN RAISE EXCEPTION 'Waiter ID not found. Refresh the waiter list.'; END IF;
  ELSE
    SELECT 'W' || lpad(g.n::text, 2, '0')
    INTO v_code
    FROM generate_series(1,999) AS g(n)
    WHERE NOT EXISTS (
      SELECT 1 FROM public.mm_waiter_directory d
      WHERE d.restaurant_id = 'a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid
        AND d.waiter_code = 'W' || lpad(g.n::text, 2, '0')
    )
    ORDER BY g.n
    LIMIT 1;
    IF v_code IS NULL THEN RAISE EXCEPTION 'No waiter IDs remain. Contact support.'; END IF;
    INSERT INTO public.mm_waiter_directory(restaurant_id, waiter_code, display_name, active)
    VALUES ('a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid, v_code, v_name, true)
    RETURNING * INTO v_row;
  END IF;

  RETURN jsonb_build_object('waiter_code',v_row.waiter_code,'display_name',v_row.display_name,
    'active',v_row.active,'created_at',v_row.created_at);
EXCEPTION
  WHEN unique_violation THEN
    RAISE EXCEPTION 'That waiter name is already in the list. Rename the existing entry instead.';
END
$$;

CREATE OR REPLACE FUNCTION public.mm_admin_set_waiter_active(
  p_waiter_code text,
  p_active boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
DECLARE
  v_role text := public.get_my_staff_role();
  v_code text := upper(btrim(coalesce(p_waiter_code,'')));
  v_has_open_visit boolean := false;
  v_row public.mm_waiter_directory%ROWTYPE;
BEGIN
  IF v_role IS DISTINCT FROM 'admin' THEN RAISE EXCEPTION 'Only the Owner/Admin can manage waiter names'; END IF;
  IF NOT coalesce(p_active,false) AND to_regclass('public.restaurant_table_visits') IS NOT NULL THEN
    IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid=to_regclass('public.restaurant_table_visits')
       AND attname='assigned_waiter_code' AND NOT attisdropped) THEN
      EXECUTE 'SELECT EXISTS (SELECT 1 FROM public.restaurant_table_visits WHERE restaurant_id=$1 AND status=''OPEN'' AND upper(assigned_waiter_code)=$2)'
        INTO v_has_open_visit
        USING 'a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid, v_code;
      IF v_has_open_visit THEN RAISE EXCEPTION 'This waiter has an open table visit. Finish those visits before deactivating this name.'; END IF;
    END IF;
  END IF;
  UPDATE public.mm_waiter_directory
  SET active = coalesce(p_active,false), updated_at = now()
  WHERE restaurant_id='a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid
    AND waiter_code=v_code
  RETURNING * INTO v_row;
  IF NOT FOUND THEN RAISE EXCEPTION 'Waiter ID not found. Refresh the waiter list.'; END IF;
  RETURN jsonb_build_object('waiter_code',v_row.waiter_code,'display_name',v_row.display_name,'active',v_row.active);
END
$$;

CREATE OR REPLACE FUNCTION public.mm_admin_export_backup()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
DECLARE
  v_restaurant_id uuid := 'a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid;
  v_name text;
  v_relation regclass;
  v_rows jsonb;
  v_data jsonb := '{}'::jsonb;
  v_missing text[] := ARRAY[]::text[];
BEGIN
  IF public.get_my_staff_role() IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Only the Owner/Admin can export a backup';
  END IF;

  FOREACH v_name IN ARRAY ARRAY[
    'restaurants','restaurant_settings','restaurant_tables','categories','menu_items','orders',
    'order_items','order_payments','order_management_audit','restaurant_table_visits',
    'mm_restaurant_notifications','mm_party_bookings','mm_restaurant_reviews','mm_restaurant_config',
    'mm_customer_profiles','mm_whatsapp_settings','mm_whatsapp_broadcast_logs','mm_waiter_directory'
  ] LOOP
    v_relation := to_regclass(format('public.%I',v_name));
    IF v_relation IS NULL THEN
      v_missing := array_append(v_missing,v_name);
      CONTINUE;
    END IF;

    IF v_name = 'restaurants' THEN
      EXECUTE 'SELECT coalesce(jsonb_agg(to_jsonb(t)), ''[]''::jsonb) FROM public.restaurants t WHERE t.id=$1'
        INTO v_rows USING v_restaurant_id;
    ELSIF v_name = 'order_items' THEN
      IF to_regclass('public.orders') IS NULL THEN
        v_rows := '[]'::jsonb;
      ELSE
        EXECUTE 'SELECT coalesce(jsonb_agg(to_jsonb(i)), ''[]''::jsonb) FROM public.order_items i JOIN public.orders o ON o.id=i.order_id WHERE o.restaurant_id=$1'
          INTO v_rows USING v_restaurant_id;
      END IF;
    ELSIF EXISTS (
      SELECT 1 FROM pg_attribute
      WHERE attrelid=v_relation AND attname='restaurant_id' AND NOT attisdropped
    ) THEN
      EXECUTE format('SELECT coalesce(jsonb_agg(to_jsonb(t)), ''[]''::jsonb) FROM public.%I t WHERE t.restaurant_id=$1',v_name)
        INTO v_rows USING v_restaurant_id;
    ELSE
      v_rows := '[]'::jsonb;
      v_missing := array_append(v_missing,v_name || ' (not restaurant-scoped)');
    END IF;
    v_data := v_data || jsonb_build_object(v_name,coalesce(v_rows,'[]'::jsonb));
  END LOOP;

  RETURN jsonb_build_object(
    'application','Mirch Masaala',
    'backup_version',1,
    'restaurant_id',v_restaurant_id,
    'exported_at',clock_timestamp(),
    'notes','JSON database export. It does not include Supabase passwords or application source code.',
    'data',v_data,
    'tables_not_available',to_jsonb(v_missing)
  );
END
$$;

