-- Mirch Masaala party booking requests.
-- Run after setup-live.sql and role-notifications.sql.
-- staff-push-notifications.sql is optional; it enables background push as well as in-app alerts.
-- Requests do not require a dine-in table. All customer writes go through a validated RPC.

BEGIN;

DO $$
BEGIN
  IF to_regclass('public.restaurants') IS NULL THEN
    RAISE EXCEPTION 'Run supabase/setup-live.sql first.';
  END IF;
  IF to_regprocedure('public.get_my_staff_role()') IS NULL THEN
    RAISE EXCEPTION 'Run supabase/setup-live.sql first so staff access can be checked.';
  END IF;
  IF to_regclass('public.mm_restaurant_notifications') IS NULL THEN
    RAISE EXCEPTION 'Run supabase/role-notifications.sql first to enable owner alerts.';
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.mm_party_bookings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  restaurant_id uuid NOT NULL REFERENCES public.restaurants(id) ON DELETE CASCADE,
  customer_name text NOT NULL,
  customer_phone text NOT NULL,
  event_type text NOT NULL CHECK (event_type IN ('Birthday','Anniversary','Family gathering','Office party','Other celebration')),
  event_date date NOT NULL,
  event_time time NOT NULL,
  guest_count integer NOT NULL CHECK (guest_count BETWEEN 1 AND 500),
  customer_notes text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW','CONTACTED','CONFIRMED','UNAVAILABLE')),
  owner_notes text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (length(trim(customer_name)) BETWEEN 1 AND 120),
  CHECK (length(trim(customer_phone)) BETWEEN 10 AND 30),
  CHECK (length(customer_notes) <= 1000),
  CHECK (length(owner_notes) <= 1000)
);

CREATE INDEX IF NOT EXISTS ix_mm_party_bookings_restaurant_date
  ON public.mm_party_bookings (restaurant_id, event_date, event_time);
CREATE INDEX IF NOT EXISTS ix_mm_party_bookings_status_created
  ON public.mm_party_bookings (restaurant_id, status, created_at DESC);

ALTER TABLE public.mm_party_bookings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.mm_party_bookings FROM PUBLIC, anon, authenticated;

-- Add the new alert type without changing existing alert rows.
DO $$
DECLARE
  v_constraint record;
BEGIN
  FOR v_constraint IN
    SELECT conname
    FROM pg_constraint
    WHERE conrelid = 'public.mm_restaurant_notifications'::regclass
      AND contype = 'c'
      AND pg_get_constraintdef(oid) ILIKE '%notification_type%'
  LOOP
    EXECUTE format('ALTER TABLE public.mm_restaurant_notifications DROP CONSTRAINT %I', v_constraint.conname);
  END LOOP;

  ALTER TABLE public.mm_restaurant_notifications
    ADD CONSTRAINT mm_restaurant_notifications_type_check
    CHECK (notification_type IN (
      'WAITER_CALL','BILL_REQUEST','NEW_ORDER','ORDER_READY','ITEM_SOLD_OUT','PARTY_BOOKING'
    ));
END
$$;

CREATE OR REPLACE FUNCTION public.mm_submit_party_booking(
  p_name text,
  p_phone text,
  p_event_type text,
  p_event_date date,
  p_event_time time,
  p_guest_count integer,
  p_notes text DEFAULT ''
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
DECLARE
  v_name text := regexp_replace(trim(coalesce(p_name, '')), '\s+', ' ', 'g');
  v_phone text := trim(coalesce(p_phone, ''));
  v_digits text;
  v_event_type text := trim(coalesce(p_event_type, ''));
  v_notes text := trim(coalesce(p_notes, ''));
  v_booking public.mm_party_bookings%ROWTYPE;
  v_reference text;
  v_notification_id bigint;
  v_dispatch_token text;
  v_ids jsonb := '[]'::jsonb;
  v_tokens jsonb := '[]'::jsonb;
  v_has_push_token boolean;
  v_message text;
BEGIN
  IF v_name = '' OR length(v_name) > 120 THEN
    RAISE EXCEPTION 'Please enter your name.';
  END IF;
  v_digits := regexp_replace(v_phone, '[^0-9]', '', 'g');
  IF length(v_digits) < 10 OR length(v_digits) > 15 OR v_phone = '' THEN
    RAISE EXCEPTION 'Please enter a valid phone number so the team can contact you.';
  END IF;
  IF v_event_type NOT IN ('Birthday','Anniversary','Family gathering','Office party','Other celebration') THEN
    RAISE EXCEPTION 'Please choose a valid occasion.';
  END IF;
  IF p_event_date IS NULL OR p_event_date < current_date THEN
    RAISE EXCEPTION 'Please choose today or a future date.';
  END IF;
  IF p_event_time IS NULL THEN
    RAISE EXCEPTION 'Please choose a preferred time.';
  END IF;
  IF p_guest_count IS NULL OR p_guest_count < 1 OR p_guest_count > 500 THEN
    RAISE EXCEPTION 'Please enter a guest count between 1 and 500.';
  END IF;
  IF length(v_notes) > 1000 THEN
    RAISE EXCEPTION 'Please keep special requests under 1,000 characters.';
  END IF;

  INSERT INTO public.mm_party_bookings (
    restaurant_id, customer_name, customer_phone, event_type,
    event_date, event_time, guest_count, customer_notes
  ) VALUES (
    'a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid,
    v_name, v_phone, v_event_type, p_event_date, p_event_time,
    p_guest_count, v_notes
  )
  RETURNING * INTO v_booking;

  v_reference := 'PARTY-' || lpad(v_booking.booking_number::text, 5, '0');
  v_message := format(
    'New party request %s — %s; %s guests; %s at %s. Please review Party Bookings.',
    v_reference, v_event_type, p_guest_count,
    to_char(p_event_date, 'DD Mon YYYY'), to_char(p_event_time, 'HH12:MI AM')
  );

  -- Store a shared owner alert. If the optional push migration is installed,
  -- return a one-time token so the existing edge function can send web push.
  SELECT EXISTS (
    SELECT 1 FROM pg_attribute
    WHERE attrelid = 'public.mm_restaurant_notifications'::regclass
      AND attname = 'push_dispatch_token' AND NOT attisdropped
  ) INTO v_has_push_token;

  IF v_has_push_token THEN
    v_dispatch_token := gen_random_uuid()::text;
    EXECUTE
      'INSERT INTO public.mm_restaurant_notifications
        (restaurant_id, target_role, notification_type, table_number, ticket_id, item_name, message, push_dispatch_token)
       VALUES ($1, ''admin'', ''PARTY_BOOKING'', '''', $2, $3, $4, $5)
       RETURNING id'
      INTO v_notification_id
      USING v_booking.restaurant_id, v_reference, v_event_type, v_message, v_dispatch_token;
    v_tokens := jsonb_build_array(jsonb_build_object('id', v_notification_id, 'token', v_dispatch_token));
  ELSE
    INSERT INTO public.mm_restaurant_notifications
      (restaurant_id, target_role, notification_type, table_number, ticket_id, item_name, message)
    VALUES
      (v_booking.restaurant_id, 'admin', 'PARTY_BOOKING', '', v_reference, v_event_type, v_message)
    RETURNING id INTO v_notification_id;
  END IF;

  v_ids := jsonb_build_array(v_notification_id);

  RETURN jsonb_build_object(
    'id', v_booking.id,
    'booking_ref', v_reference,
    'name', v_booking.customer_name,
    'phone', v_booking.customer_phone,
    'event_type', v_booking.event_type,
    'event_date', v_booking.event_date,
    'event_time', to_char(v_booking.event_time, 'HH24:MI'),
    'guest_count', v_booking.guest_count,
    'notes', v_booking.customer_notes,
    'status', v_booking.status,
    'created_at', v_booking.created_at,
    'notification_ids', v_ids,
    'dispatch_tokens', v_tokens
  );
END
$$;

CREATE OR REPLACE FUNCTION public.mm_admin_list_party_bookings(p_limit integer DEFAULT 100)
RETURNS TABLE (
  id uuid,
  booking_ref text,
  customer_name text,
  customer_phone text,
  event_type text,
  event_date date,
  event_time text,
  guest_count integer,
  customer_notes text,
  status text,
  owner_notes text,
  created_at timestamptz,
  updated_at timestamptz
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
BEGIN
  IF public.get_my_staff_role() IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Owner/Admin access required.';
  END IF;

  RETURN QUERY
  SELECT b.id,
         'PARTY-' || lpad(b.booking_number::text, 5, '0'),
         b.customer_name, b.customer_phone, b.event_type, b.event_date,
         to_char(b.event_time, 'HH24:MI'),
         b.guest_count, b.customer_notes, b.status, b.owner_notes, b.created_at, b.updated_at
  FROM public.mm_party_bookings b
  WHERE b.restaurant_id = 'a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid
  ORDER BY b.created_at DESC
  LIMIT greatest(1, least(coalesce(p_limit, 100), 250));
END
$$;

CREATE OR REPLACE FUNCTION public.mm_admin_update_party_booking(
  p_booking_id uuid,
  p_status text,
  p_owner_notes text DEFAULT ''
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
DECLARE
  v_status text := upper(trim(coalesce(p_status, '')));
  v_booking public.mm_party_bookings%ROWTYPE;
BEGIN
  IF public.get_my_staff_role() IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Owner/Admin access required.';
  END IF;
  IF v_status NOT IN ('NEW','CONTACTED','CONFIRMED','UNAVAILABLE') THEN
    RAISE EXCEPTION 'Choose a valid booking status.';
  END IF;
  IF length(trim(coalesce(p_owner_notes, ''))) > 1000 THEN
    RAISE EXCEPTION 'Please keep internal notes under 1,000 characters.';
  END IF;

  UPDATE public.mm_party_bookings
  SET status = v_status,
      owner_notes = trim(coalesce(p_owner_notes, '')),
      updated_at = now()
  WHERE id = p_booking_id
    AND restaurant_id = 'a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid
  RETURNING * INTO v_booking;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Party booking not found.';
  END IF;

  RETURN jsonb_build_object(
    'id', v_booking.id,
    'booking_ref', 'PARTY-' || lpad(v_booking.booking_number::text, 5, '0'),
    'status', v_booking.status,
    'owner_notes', v_booking.owner_notes,
    'updated_at', v_booking.updated_at
  );
END
$$;

REVOKE ALL ON FUNCTION public.mm_submit_party_booking(text, text, text, date, time, integer, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.mm_submit_party_booking(text, text, text, date, time, integer, text) TO anon, authenticated;
