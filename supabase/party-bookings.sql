REVOKE ALL ON FUNCTION public.mm_admin_update_party_booking(uuid, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.mm_admin_update_party_booking(uuid, text, text) TO authenticated;

NOTIFY pgrst, 'reload schema';
COMMIT;
