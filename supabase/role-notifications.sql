-- Mirch Masaala: role-based live alerts for waiter calls, kitchen tickets and owner actions.
-- Run this once in the Supabase SQL Editor AFTER setup-live.sql.
-- Safe to re-run.

BEGIN;

CREATE TABLE IF NOT EXISTS public.mm_restaurant_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id uuid NOT NULL REFERENCES public.restaurants(id) ON DELETE CASCADE,
  target_role text NOT NULL CHECK (target_role IN ('admin', 'waiter', 'kitchen')),
  notification_type text NOT NULL CHECK (notification_type IN (
    'WAITER_CALL', 'BILL_REQUEST', 'NEW_ORDER', 'ORDER_READY', 'ITEM_SOLD_OUT'
  )),
  table_number text NOT NULL DEFAULT '',
  ticket_id text NOT NULL DEFAULT '',
  item_name text NOT NULL DEFAULT '',
  message text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz,
  resolved_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS ix_mm_restaurant_notifications_open
  ON public.mm_restaurant_notifications (restaurant_id, target_role, created_at DESC)
  WHERE resolved_at IS NULL;

ALTER TABLE public.mm_restaurant_notifications ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.mm_restaurant_notifications FROM PUBLIC, anon, authenticated;

-- Guest devices may only create the two safe front-of-house requests.
-- Rate-limit duplicate taps while an earlier request is still open.
CREATE OR REPLACE FUNCTION public.mm_create_guest_notification(
  p_restaurant_id uuid,
  p_type text,
  p_table_number text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
DECLARE
  v_type text := upper(coalesce(p_type, ''));
  v_table text := lpad(trim(coalesce(p_table_number, '')), 2, '0');
  v_role text;
  v_existing bigint;
  v_id bigint;
  v_ids bigint[] := ARRAY[]::bigint[];
BEGIN
  IF p_restaurant_id IS DISTINCT FROM 'a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid THEN
    RAISE EXCEPTION 'Unknown restaurant';
  END IF;
  IF v_type NOT IN ('WAITER_CALL', 'BILL_REQUEST') THEN
    RAISE EXCEPTION 'Unsupported guest request';
  END IF;
  IF v_table !~ '^[0-9]{2}$' OR NOT EXISTS (
    SELECT 1 FROM public.restaurant_tables t
    WHERE t.restaurant_id = p_restaurant_id
      AND lpad(t.table_number::text, 2, '0') = v_table
      AND t.is_active = true
  ) THEN
    RAISE EXCEPTION 'Choose a valid active table';
  END IF;

  FOREACH v_role IN ARRAY
    CASE WHEN v_type = 'WAITER_CALL'
      THEN ARRAY['waiter']::text[]
      ELSE ARRAY['waiter', 'admin']::text[]
    END
  LOOP
    SELECT n.id INTO v_existing
    FROM public.mm_restaurant_notifications n
    WHERE n.restaurant_id = p_restaurant_id
      AND n.target_role = v_role
      AND n.notification_type = v_type
      AND n.table_number = v_table
      AND n.resolved_at IS NULL
      AND n.created_at >= now() - interval '30 seconds'
    ORDER BY n.created_at DESC
    LIMIT 1;

    IF v_existing IS NOT NULL THEN
      v_ids := array_append(v_ids, v_existing);
      v_existing := NULL;
    ELSE
      INSERT INTO public.mm_restaurant_notifications (
        restaurant_id, target_role, notification_type, table_number, message
      ) VALUES (
        p_restaurant_id, v_role, v_type, v_table,
        CASE WHEN v_type = 'WAITER_CALL' THEN 'Guest needs a waiter'
             ELSE 'Guest requested the bill' END
      )
      RETURNING id INTO v_id;
      v_ids := array_append(v_ids, v_id);
    END IF;
  END LOOP;

  RETURN jsonb_build_object('ok', true, 'notification_ids', to_jsonb(v_ids));
END
$$;

REVOKE ALL ON FUNCTION public.mm_create_guest_notification(uuid, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.mm_create_guest_notification(uuid, text, text) TO anon, authenticated;

-- Staff can only read unresolved notifications for their own role.
CREATE OR REPLACE FUNCTION public.mm_staff_notifications(p_limit integer DEFAULT 30)
RETURNS TABLE (
  id bigint,
  target_role text,
  notification_type text,
  table_number text,
  ticket_id text,
  item_name text,
  message text,
  created_at timestamptz
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
DECLARE
  v_role text := public.get_my_staff_role();
BEGIN
  IF v_role IS NULL OR v_role NOT IN ('admin', 'waiter', 'kitchen') THEN
    RAISE EXCEPTION 'Staff sign-in required';
  END IF;

  RETURN QUERY
  SELECT n.id, n.target_role, n.notification_type, n.table_number,
         n.ticket_id, n.item_name, n.message, n.created_at
  FROM public.mm_restaurant_notifications n
  WHERE n.restaurant_id = 'a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid
    AND n.target_role = v_role
    AND n.resolved_at IS NULL
  ORDER BY n.created_at DESC
  LIMIT greatest(1, least(coalesce(p_limit, 30), 100));
END
$$;

REVOKE ALL ON FUNCTION public.mm_staff_notifications(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.mm_staff_notifications(integer) TO authenticated;

CREATE OR REPLACE FUNCTION public.mm_resolve_staff_notification(p_notification_id bigint)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
DECLARE
  v_role text := public.get_my_staff_role();
BEGIN
  IF v_role IS NULL OR v_role NOT IN ('admin', 'waiter', 'kitchen') THEN
    RAISE EXCEPTION 'Staff sign-in required';
  END IF;

  UPDATE public.mm_restaurant_notifications
  SET resolved_at = now(), resolved_by = auth.uid()
  WHERE id = p_notification_id
    AND restaurant_id = 'a3702d10-6673-4c06-9783-1d61c945ecd5'::uuid
    AND target_role = v_role
    AND resolved_at IS NULL;

  RETURN FOUND;
END
$$;

REVOKE ALL ON FUNCTION public.mm_resolve_staff_notification(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.mm_resolve_staff_notification(bigint) TO authenticated;

-- Every new ticket produces one kitchen alert; tickets themselves remain the source of truth.
CREATE OR REPLACE FUNCTION public.mm_notify_kitchen_new_order()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
DECLARE
  v_table text;
BEGIN
  SELECT lpad(t.table_number::text, 2, '0') INTO v_table
  FROM public.restaurant_tables t
  WHERE t.id = NEW.table_id;

  INSERT INTO public.mm_restaurant_notifications (
    restaurant_id, target_role, notification_type, table_number, ticket_id, message
  ) VALUES (
    NEW.restaurant_id, 'kitchen', 'NEW_ORDER', coalesce(v_table, ''),
    coalesce(NEW.ticket_id, ''), 'New order received'
  );
  RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS mm_notify_kitchen_new_order_trigger ON public.orders;
CREATE TRIGGER mm_notify_kitchen_new_order_trigger
AFTER INSERT ON public.orders
FOR EACH ROW EXECUTE FUNCTION public.mm_notify_kitchen_new_order();

-- Notify waiter and owner only when an order becomes ready, not for every status change.
CREATE OR REPLACE FUNCTION public.mm_notify_order_ready()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
DECLARE
  v_table text;
  v_role text;
BEGIN
  IF upper(coalesce(NEW.status::text, '')) <> 'READY'
     OR upper(coalesce(OLD.status::text, '')) = 'READY' THEN
    RETURN NEW;
  END IF;

  SELECT lpad(t.table_number::text, 2, '0') INTO v_table
  FROM public.restaurant_tables t WHERE t.id = NEW.table_id;

  FOREACH v_role IN ARRAY ARRAY['waiter', 'admin']::text[] LOOP
    INSERT INTO public.mm_restaurant_notifications (
      restaurant_id, target_role, notification_type, table_number, ticket_id, message
    ) VALUES (
      NEW.restaurant_id, v_role, 'ORDER_READY', coalesce(v_table, ''),
      coalesce(NEW.ticket_id, ''), 'Order ready to serve'
    );
  END LOOP;
  RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS mm_notify_order_ready_trigger ON public.orders;
CREATE TRIGGER mm_notify_order_ready_trigger
AFTER UPDATE OF status ON public.orders
FOR EACH ROW EXECUTE FUNCTION public.mm_notify_order_ready();

-- When the kitchen marks an item sold out, make it visible in the owner's live alert queue.
CREATE OR REPLACE FUNCTION public.mm_notify_menu_sold_out()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'pg_catalog, public, pg_temp'
AS $$
BEGIN
  IF OLD.is_available IS TRUE AND NEW.is_available IS FALSE THEN
    INSERT INTO public.mm_restaurant_notifications (
      restaurant_id, target_role, notification_type, item_name, message
    ) VALUES (
      NEW.restaurant_id, 'admin', 'ITEM_SOLD_OUT', left(coalesce(NEW.name, 'Menu item'), 160),
      left(coalesce(NEW.name, 'A menu item') || ' was marked sold out by the kitchen', 240)
    );
  END IF;
  RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS mm_notify_menu_sold_out_trigger ON public.menu_items;
CREATE TRIGGER mm_notify_menu_sold_out_trigger
AFTER UPDATE OF is_available ON public.menu_items
FOR EACH ROW EXECUTE FUNCTION public.mm_notify_menu_sold_out();

COMMIT;
